"""Interactive backend: saspy HTTP access method -> Viya Compute Service.

One ``InteractiveSession`` == one compute session (one compute pod). Datasets
are moved as raw ``.sas7bdat`` files with ``saspy.upload``/``download`` so
formats, labels and lengths survive unchanged.
"""

from __future__ import annotations

import logging
import secrets
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from . import auth
from .config import Config, config_dir
from .logs import LogSummary, scan_log
from .transfer import DEFAULT_LIBREF, parse_ds_ref, resolve_remote_root, sas_quote, split_sas_file

logging.getLogger("saspy").setLevel(logging.WARNING)


class SASError(Exception):
    def __init__(self, msg: str, log: str = ""):
        super().__init__(msg)
        self.log = log


def write_saspy_cfg(cfg: Config) -> Path:
    """Write a minimal saspy config module (no secrets) and return its path."""
    viya: dict = {"url": cfg.viya.url, "verify": cfg.viya.verify, "pkce": True}
    if cfg.viya.context:
        viya["context"] = cfg.viya.context
    if cfg.viya.cafile:
        viya["cafile"] = cfg.viya.cafile
    path = config_dir() / "sascfg_vsub.py"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by vsub - do not edit; edit config.toml instead.\n"
        "SAS_config_names = ['viya']\n"
        "SAS_config_options = {'lock_down': False, 'verbose': False}\n"
        f"viya = {viya!r}\n"
    )
    return path


def _default_factory(cfg: Config, tokens: auth.Tokens):
    import saspy

    return saspy.SASsession(
        cfgfile=str(write_saspy_cfg(cfg)),
        cfgname="viya",
        results="TEXT",
        authtoken=tokens.access_token,
        refreshtoken=tokens.refresh_token,
    )


class InteractiveSession:
    def __init__(self, cfg: Config, factory: Callable | None = None, tokens: auth.Tokens | None = None):
        self.cfg = cfg
        self._factory = factory or _default_factory
        self._tokens = tokens
        self.sas = None
        self._root: str | None = None

    # -- lifecycle -----------------------------------------------------------
    def __enter__(self) -> "InteractiveSession":
        tokens = self._tokens or auth.get_tokens(self.cfg.viya)
        self._tokens = tokens
        try:
            self.sas = self._factory(self.cfg, tokens)
        except Exception as e:  # saspy raises assorted connection/auth errors
            raise SASError(f"Could not start a SAS compute session at {self.cfg.viya.url}: {type(e).__name__}: {e}") from None
        if self.sas is None or getattr(self.sas, "_io", True) is None:
            raise SASError("Could not start a SAS compute session (see messages above).")
        return self

    def __exit__(self, *exc) -> None:
        self._persist_refreshed_tokens()
        try:
            self.sas.endsas()
        except Exception:
            pass

    def _persist_refreshed_tokens(self) -> None:
        """saspy refreshes tokens on long sessions; keep the newest pair."""
        try:
            scfg = self.sas._io.sascfg
            tok, ref = scfg._token, scfg._refresh
        except AttributeError:
            return
        if tok and self._tokens and (tok, ref) != (self._tokens.access_token, self._tokens.refresh_token):
            auth.save_tokens(auth.Tokens(self.cfg.viya.url, tok, ref or self._tokens.refresh_token))

    # -- primitives ----------------------------------------------------------
    def submit(self, code: str, check: bool = True, what: str = "SAS step") -> dict:
        res = self.sas.submit(code, results="TEXT")
        if check:
            summary = scan_log(res.get("LOG", ""))
            if summary.errors:
                raise SASError(f"{what} failed:\n  " + "\n  ".join(summary.errors), res.get("LOG", ""))
        return res

    def macro_value(self, expr: str) -> str:
        """Evaluate a macro expression (e.g. ``%sysget(HOME)``) and return it as text."""
        self.submit(f"%let _vsubv={expr};", what=f"evaluating {expr}")
        val = self.sas.symget("_vsubv", outtype='str')
        return "" if val is None else str(val).strip()

    def home(self) -> str:
        home = self.macro_value("%sysget(HOME)")
        if not home:
            raise SASError("HOME is not set in the compute session.")
        return home

    def hostname(self) -> str:
        return self.macro_value("%sysget(HOSTNAME)")

    def root(self) -> str:
        if self._root is None:
            self._root = resolve_remote_root(self.cfg.storage.remote_root, self.home())
        return self._root

    def ensure_root(self, libref: str = DEFAULT_LIBREF) -> str:
        """Create remote_root (mkdir -p) and assign ``libname vsub`` to it."""
        root = self.root()
        q = sas_quote(root)
        code = f"""
data _null_;
  length root cur parent rc $1024 part $256;
  root = {q};
  cur = '';
  do i = 1 to countw(root, '/');
    part = scan(root, i, '/');
    parent = cur;
    if parent = '' then parent = '/';
    cur = cats(cur, '/', part);
    if fileexist(cur) = 0 then do;
      rc = dcreate(part, parent);
      if rc = '' then put 'ERR' 'OR: vsub could not create directory ' cur;
    end;
  end;
run;
libname {libref} {q};
"""
        self.submit(code, what=f"assigning libname {libref} to {root}")
        return root

    def lib_path(self, libref: str) -> str:
        path = self.macro_value(f"%sysfunc(pathname({libref}))")
        if not path:
            raise SASError(f"Library {libref!r} is not assigned in this session.")
        if path.startswith("("):
            raise SASError(f"Library {libref!r} is a concatenation {path}; copy the dataset to vsub or work first.")
        return path

    def upload_file(self, local: Path, remote: str) -> None:
        res = self.sas.upload(str(local), remote, overwrite=True)
        if not res.get("Success"):
            raise SASError(f"upload of {local} -> {remote} failed", res.get("LOG", ""))

    def download_file(self, remote: str, local: Path) -> None:
        local.parent.mkdir(parents=True, exist_ok=True)
        res = self.sas.download(str(local), remote, overwrite=True)
        if not res.get("Success"):
            raise SASError(f"download of {remote} -> {local} failed", res.get("LOG", ""))

    def listdir(self, path: str) -> list[str]:
        items = self.sas.dirlist(path)
        if items is None:
            raise SASError(f"cannot list {path} (missing or not accessible)")
        return sorted(items)

    # -- dataset-level operations ---------------------------------------------
    def upload_dataset(self, local: Path, subdir: str | None = None) -> str:
        member, ext = split_sas_file(local)
        target_dir = self.root() if not subdir else f"{self.root()}/{subdir.strip('/')}"
        remote = f"{target_dir}/{member}{ext}"
        self.upload_file(local, remote)
        return remote

    def download_dataset(self, ref: str, to_dir: Path) -> Path:
        lib, member = parse_ds_ref(ref)
        remote_dir = self.root() if lib == DEFAULT_LIBREF and self._root else self.lib_path(lib)
        local = to_dir / f"{member}.sas7bdat"
        self.download_file(f"{remote_dir}/{member}.sas7bdat", local)
        return local

    def delete_dataset(self, ref: str) -> None:
        lib, member = parse_ds_ref(ref)
        self.submit(
            f"proc datasets lib={lib} nolist nowarn; delete {member}; quit;",
            what=f"deleting {lib}.{member}",
        )


# --- high-level flows ---------------------------------------------------------

@dataclass
class RunResult:
    log: str
    lst: str
    session_log: str
    summary: LogSummary
    uploaded: list[str] = field(default_factory=list)
    downloaded: list[Path] = field(default_factory=list)


def run_program(
    session: InteractiveSession,
    code: str,
    uploads: list[Path],
    downloads: list[str],
    download_dir: Path,
) -> RunResult:
    """Upload inputs, run ``code``, download outputs. Session must be open."""
    session.ensure_root()
    uploaded = [session.upload_dataset(p) for p in uploads]

    res = session.submit(code, check=False)
    log, lst = res.get("LOG", ""), res.get("LST", "")
    summary = scan_log(log)

    downloaded: list[Path] = []
    for ref in downloads:
        try:
            downloaded.append(session.download_dataset(ref, download_dir))
        except SASError as e:
            summary.errors.append(f"ERROR: vsub: {e}")

    return RunResult(log, lst, session.sas.saslog(), summary, uploaded, downloaded)


@dataclass
class HomeCheck:
    home: str
    root: str
    host1: str
    host2: str
    persistent: bool
    detail: str


def check_home(cfg: Config, factory: Callable | None = None) -> HomeCheck:
    """Write a marker in HOME, start a *new* session (new pod) and look for it."""
    token = secrets.token_hex(8)
    with InteractiveSession(cfg, factory) as s1:
        home = s1.home()
        root = s1.root()
        host1 = s1.hostname()
        marker = f"{home}/.vsub_persist_check"
        s1.submit(
            f"data _null_; file {sas_quote(marker)}; put '{token}'; run;",
            what=f"writing marker file in {home}",
        )
        s1.ensure_root()  # also verifies remote_root can be created + assigned

    with InteractiveSession(cfg, factory, tokens=s1._tokens) as s2:
        host2 = s2.hostname()
        s2.submit("%let _vsubtok=;", what="init")
        s2.submit(
            f"""data _null_;
  length t $64;
  if fileexist({sas_quote(marker)}) then do;
    infile {sas_quote(marker)} truncover;
    input t $64.;
    call symputx('_vsubtok', t);
  end;
  stop;
run;""",
            check=False,
        )
        found = str(s2.sas.symget("_vsubtok", outtype='str') or "").strip()
        s2.submit(
            f"data _null_; rc = filename('_vsubm', {sas_quote(marker)}); rc = fdelete('_vsubm'); run;",
            check=False,
        )

    persistent = found == token
    if persistent and host1 == host2:
        detail = "marker survived, but both sessions ran on the same host - restart test after the pod is recycled to be sure"
    elif persistent:
        detail = "marker written in one compute pod was visible from a different pod"
    else:
        detail = "marker written in the first session was NOT visible in the second - HOME is ephemeral"
    return HomeCheck(home, root, host1, host2, persistent, detail)
